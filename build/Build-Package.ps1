#Requires -Version 5.1
<#
.SYNOPSIS
    Builds the single-file script and the PowerShell module from the sources.

.DESCRIPTION
    Sources stay the single source of truth (Invoke-ADAudit.ps1, lib/, Scanners/).
    This script generates:

      dist/dtecht-AD.ps1                 one file with everything inline - copy it anywhere and run
      dist/dtecht-AD/dtecht-AD.psm1      module: Import-Module, then Invoke-DtechtAD (alias dtecht-ad)
      dist/dtecht-AD/dtecht-AD.psd1      module manifest
      dist/SHA256SUMS                    hashes of the files above

    The parameter block and help are taken from Invoke-ADAudit.ps1 with the PowerShell
    parser, and the '#region loader' block (dot-sourcing lib/ and Scanners/) is replaced
    by the files' contents. Files are written as UTF-8 with BOM for Windows PowerShell 5.1.

.PARAMETER Check
    Build into a temp folder and fail (exit 1) if dist/ is out of date. Use before merging.

.EXAMPLE
    pwsh -File build/Build-Package.ps1
.EXAMPLE
    pwsh -File build/Build-Package.ps1 -Check
#>
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$moduleGuid = '6f1c9d2e-3b7a-4e58-9c41-0d2a7be5f913'
$nl = "`r`n"

function Get-SourceBody([string]$Path) {
    # File contents without '#Requires' lines, CRLF line endings
    $lines = (Get-Content -LiteralPath $Path -Raw -Encoding UTF8) -split "`r?`n"
    (($lines | Where-Object { $_ -notmatch '^\s*#Requires\b' }) -join $nl).Trim()
}

$runnerPath = Join-Path $root 'Invoke-ADAudit.ps1'
$runnerText = (Get-Content -LiteralPath $runnerPath -Raw -Encoding UTF8) -replace "`r?`n", $nl
$tokens = $null; $errs = $null
$ast = [System.Management.Automation.Language.Parser]::ParseInput($runnerText, [ref]$tokens, [ref]$errs)
if ($errs) { throw "Invoke-ADAudit.ps1 does not parse: $($errs[0].Message)" }

$help = [regex]::Match($runnerText, '(?s)<#.*?#>').Value
$paramBlock = $ast.ParamBlock.Extent.Text
if ($paramBlock -notmatch '^\[CmdletBinding') { $paramBlock = "[CmdletBinding()]$nl$paramBlock" }
$body = $runnerText.Substring($ast.ParamBlock.Extent.EndOffset).Trim()
if ($body -notmatch '(?s)#region loader.*?#endregion loader') { throw "Invoke-ADAudit.ps1 has no '#region loader' block" }
$body = [regex]::Replace($body, '(?s)#region loader.*?#endregion loader\r?\n', '')
if ($body -match '(?m)^\s*exit\b') { throw "Invoke-ADAudit.ps1 uses 'exit' - not allowed inside the module function" }
$version = [regex]::Match($runnerText, "Version\s*=\s*'([\d.]+)'").Groups[1].Value
if (-not $version) { throw 'Version not found in Invoke-ADAudit.ps1 ($meta.Version)' }

$sources = @()
foreach ($lib in 'Common', 'Native', 'Acl', 'Compare', 'Remediation') { $sources += Join-Path $root "lib/$lib.ps1" }
$sources += @(Get-ChildItem -Path (Join-Path $root 'Scanners') -Filter '*.ps1' | Sort-Object Name | ForEach-Object { $_.FullName })
$inline = foreach ($s in $sources) {
    $rel = $s.Substring($root.Length + 1) -replace '\\', '/'
    "#region $rel$nl$(Get-SourceBody $s)$nl#endregion $rel"
}
$inline = $inline -join "$nl$nl"
$banner = "# dtecht-AD $version - generated by build/Build-Package.ps1 from https://github.com/techdetechtives/dtecht-AD. Do not edit; edit the sources and rebuild.$nl# Read-only Active Directory audit. MIT License."

$script = @(
    '#Requires -Version 5.1', $banner, $help, $paramBlock, '',
    $inline, '', '#region runner', $body, '#endregion runner', ''
) -join $nl

$functionHelp = $help -replace '\.\\Invoke-ADAudit\.ps1', 'Invoke-DtechtAD'
$module = @(
    '#Requires -Version 5.1', $banner, '',
    $inline, '', '#region runner',
    'function Invoke-DtechtAD {', $functionHelp, $paramBlock, '', $body, '}',
    '#endregion runner', '',
    "Set-Alias -Name 'dtecht-ad' -Value 'Invoke-DtechtAD'",
    "Export-ModuleMember -Function 'Invoke-DtechtAD' -Alias 'dtecht-ad'", ''
) -join $nl

$manifest = @"
@{
    RootModule           = 'dtecht-AD.psm1'
    ModuleVersion        = '$version'
    GUID                 = '$moduleGuid'
    Author               = 'TechDetechtives'
    CompanyName          = 'TechDetechtives'
    Copyright            = '(c) 2026 TechDetechtives. MIT License.'
    Description          = 'Read-only Active Directory security audit: accounts, groups, ACLs/DCSync, GPO audit policy, DC events, host checks, risk score and run-to-run comparison. Nothing is written to AD or scanned hosts.'
    PowerShellVersion    = '5.1'
    CompatiblePSEditions = @('Desktop', 'Core')
    FunctionsToExport    = @('Invoke-DtechtAD')
    AliasesToExport      = @('dtecht-ad')
    CmdletsToExport      = @()
    VariablesToExport    = @()
    PrivateData          = @{
        PSData = @{
            Tags         = @('ActiveDirectory', 'Security', 'Audit', 'BlueTeam', 'PingCastle', 'DCSync', 'Windows', 'PSEdition_Desktop', 'PSEdition_Core')
            LicenseUri   = 'https://github.com/techdetechtives/dtecht-AD/blob/main/LICENSE'
            ProjectUri   = 'https://github.com/techdetechtives/dtecht-AD'
            ReleaseNotes = 'Read-only AD audit. Run: dtecht-ad -Preset ADOnly -OpenReport. Changes: https://github.com/techdetechtives/dtecht-AD/commits/main'
        }
    }
}
"@ -replace "`r?`n", $nl

# Sanity: generated code must parse
foreach ($pair in @(@('dtecht-AD.ps1', $script), @('dtecht-AD.psm1', $module))) {
    $e = $null; $t = $null
    [void][System.Management.Automation.Language.Parser]::ParseInput($pair[1], [ref]$t, [ref]$e)
    if ($e) { throw "$($pair[0]) does not parse: $($e[0].Message) at line $($e[0].Extent.StartLineNumber)" }
}

$outRoot = $(if ($Check) { Join-Path ([System.IO.Path]::GetTempPath()) ("dtecht-ad-build-" + [guid]::NewGuid()) } else { Join-Path $root 'dist' })
$files = [ordered]@{
    'dtecht-AD.ps1'           = $script
    'dtecht-AD/dtecht-AD.psm1' = $module
    'dtecht-AD/dtecht-AD.psd1' = $manifest
}
$utf8Bom = New-Object System.Text.UTF8Encoding($true)
New-Item -ItemType Directory -Path (Join-Path $outRoot 'dtecht-AD') -Force | Out-Null
$sums = foreach ($rel in $files.Keys) {
    $path = Join-Path $outRoot $rel
    [System.IO.File]::WriteAllText($path, $files[$rel], $utf8Bom)
    '{0}  {1}' -f (Get-FileHash -Algorithm SHA256 -LiteralPath $path).Hash.ToLowerInvariant(), $rel
}
[System.IO.File]::WriteAllText((Join-Path $outRoot 'SHA256SUMS'), (($sums -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding($false)))

if ($Check) {
    $stale = @()
    foreach ($rel in @($files.Keys) + 'SHA256SUMS') {
        $a = Join-Path $outRoot $rel; $b = Join-Path (Join-Path $root 'dist') $rel
        if (-not (Test-Path $b) -or (Get-FileHash $a).Hash -ne (Get-FileHash $b).Hash) { $stale += $rel }
    }
    Remove-Item -Recurse -Force $outRoot
    if ($stale) { Write-Host "dist/ is out of date: $($stale -join ', '). Run build/Build-Package.ps1 and commit." -ForegroundColor Red; exit 1 }
    Write-Host "dist/ is up to date (version $version)." -ForegroundColor Green
}
else {
    Write-Host "Built dtecht-AD $version into dist/:" -ForegroundColor Green
    $sums | ForEach-Object { Write-Host "  $_" }
}
